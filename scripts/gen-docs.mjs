#!/usr/bin/env node
// Generates data/coverage.json, docs/COVERAGE.md and docs/SEVERITY.md (no guideline text: ids, links, our own words),
// plus docs/local/*.md with the rule titles for local review (git-ignored: the guideline's license is internal-use only).
import { mkdirSync, writeFileSync } from 'node:fs';
import { computeCoverage } from './coverage.mjs';

const cov = computeCoverage();
if (cov.unknown.length > 0) {
  console.error('Unknown rule ids referenced in src/rules:\n  ' + cov.unknown.join('\n  '));
  process.exit(1);
}
const { rows, status, baseUrl, commit } = cov;
const link = (r) => `[${r.id}](${baseUrl}#${r.anchor})`;
const sections = [...new Set(rows.map((r) => r.section))];
const realRules = rows.filter((r) => r.kind === 'rule');
const count = (f) => realRules.filter(f).length;

mkdirSync('docs/local', { recursive: true });
mkdirSync('data', { recursive: true });

const summary = {
  guidelineCommit: commit,
  rules: realRules.length,
  implemented: count((r) => r.state === 'implemented'),
  clangTidyOnly: count((r) => r.state === 'clang-tidy'),
  notImplemented: count((r) => r.state === 'not-implemented'),
  byReason: Object.fromEntries(Object.keys(status.reasons).map((k) => [k, count((r) => r.reason === k)]).filter(([, n]) => n > 0)),
  errors: count((r) => r.severity === 'error'),
  warnings: count((r) => r.severity === 'warning'),
};
writeFileSync('data/coverage.json', JSON.stringify({ summary, rules: rows.map(({ title, ...r }) => r) }, null, 1) + '\n');

function coverageDoc(withTitles) {
  const out = [];
  out.push('# Coverage of the C++ Core Guidelines', '');
  out.push(`Generated by \`npm run docs:coverage\` from the guideline at commit \`${commit}\`.`);
  out.push(withTitles ? '' : 'Rule titles are not reproduced here: follow the links to the official text.', '');
  out.push('## Summary', '');
  out.push('| | Rules |', '|---|---:|');
  out.push(`| Rules in the guideline (excluding FAQ and non-rules) | ${summary.rules} |`);
  out.push(`| **Implemented by the built-in analyser** | **${summary.implemented}** |`);
  out.push(`| Implemented only through the optional clang-tidy bridge | ${summary.clangTidyOnly} |`);
  out.push(`| Not implemented | ${summary.notImplemented} |`, '');
  out.push('Why a rule is not implemented (answer 1A: only rules with an objective, decidable criterion are checked):', '');
  out.push('| Reason | Rules | Meaning |', '|---|---:|---|');
  for (const [k, n] of Object.entries(summary.byReason)) out.push(`| \`${k}\` | ${n} | ${status.reasons[k]} |`);
  out.push('', '`implemented` means the rule is reported by a built-in check, possibly as one of several rules violated by the same construct. Notes list the interpretation chosen wherever the guideline leaves room.', '');
  out.push('## Extension rules (`CPP20.*`, answer 5)', '');
  out.push('Not part of the Core Guidelines: C++20 modernisations. They are always warnings.', '');
  out.push('| Rule | Severity | What it does |', '|---|---|---|');
  for (const id of cov.extension) out.push(`| \`${id}\` | ${id === 'CPP20.suppress' ? 'error' : 'warning'} | ${status.extension[id] ?? ''} |`);
  out.push('');
  for (const s of sections) {
    const list = rows.filter((r) => r.section === s && r.kind === 'rule');
    if (list.length === 0) continue;
    out.push(`## ${s}`, '');
    out.push(withTitles ? '| Rule | Title | Severity | Status | Notes |' : '| Rule | Severity | Status | Notes |');
    out.push(withTitles ? '|---|---|---|---|---|' : '|---|---|---|---|');
    for (const r of list) {
      const st = r.state === 'implemented' ? (r.clangTidy ? 'implemented (+ clang-tidy)' : 'implemented') : r.state === 'clang-tidy' ? 'clang-tidy only' : `not implemented: \`${r.reason}\``;
      const cells = [link(r), ...(withTitles ? [(r.title ?? '').replace(/\|/g, '\\|')] : []), r.severity, st, (r.note ?? '').replace(/\|/g, '\\|')];
      out.push(`| ${cells.join(' | ')} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

function severityDoc(withTitles) {
  const out = [];
  out.push('# Error or warning? (answer 3A)', '');
  out.push('The guideline has no formal "optional" category, so the severity of each rule is derived from its own wording:', '');
  out.push('* **warning** when the rule says it is only a recommendation (`This is a recommendation for when you have no constraints or better ideas`, used by the naming/layout rules), or when its title contains *prefer*, *consider*, *avoid*, *favor*, *should* or *ideally*;');
  out.push('* **error** for everything else (`Don\'t…`, `Never…`, `Use…`, `Always…`, `Make…`, …).', '');
  out.push('Warnings disappear when `cpp20Guidelines.enableOptionalWarnings` is off; errors never do. The `CPP20.*` modernisations are always warnings.', '');
  out.push(`${summary.errors} errors and ${summary.warnings} warnings in total.`, '');
  out.push('To change a classification, edit `scripts/extract-rules.mjs` (the keyword list) and run `npm run rules:extract && npm run docs:coverage`.', '');
  for (const s of sections) {
    const list = rows.filter((r) => r.section === s && r.kind === 'rule');
    if (list.length === 0) continue;
    out.push(`## ${s}`, '');
    out.push(withTitles ? '| Rule | Title | Severity | Decided by |' : '| Rule | Severity | Decided by |');
    out.push(withTitles ? '|---|---|---|---|' : '|---|---|---|');
    for (const r of list) {
      const why = r.severityReason === 'default' ? 'default (error)' : r.severityReason === 'explicit-recommendation' ? 'text: "recommendation"' : `title: "${r.severityReason.split(':')[1]}"`;
      out.push(`| ${[link(r), ...(withTitles ? [(r.title ?? '').replace(/\|/g, '\\|')] : []), r.severity, why].join(' | ')} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

writeFileSync('docs/COVERAGE.md', coverageDoc(false));
writeFileSync('docs/SEVERITY.md', severityDoc(false));
if (rows.some((r) => r.title)) {
  writeFileSync('docs/local/COVERAGE-with-titles.md', coverageDoc(true));
  writeFileSync('docs/local/SEVERITY-with-titles.md', severityDoc(true));
}
console.log(JSON.stringify(summary, null, 1));
